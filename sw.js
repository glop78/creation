self.addEventListener('install', function (evenement) {
  evenement.waitUntil(
    caches.open(CACHE).then(function (cache) {
      return cache.addAll(A_METTRE_EN_CACHE);
    }).then(function () { return self.skipWaiting(); })
  );
});

self.addEventListener('activate', function (evenement) {
  evenement.waitUntil(
    caches.keys().then(function (cles) {
      return Promise.all(cles.map(function (cle) {
        if (cle.indexOf('creatio-') === 0 && cle !== CACHE) {
          return caches.delete(cle);
        }
        return null;
      }));
    }).then(function () { return self.clients.claim(); })
  );
});

self.addEventListener('fetch', function (evenement) {
  var requete = evenement.request;
  if (requete.method !== 'GET') { return; }

  var url = new URL(requete.url);
  if (url.origin !== self.location.origin) { return; }

  evenement.respondWith(
    caches.match(requete).then(function (enCache) {
      var reseau = fetch(requete).then(function (reponse) {
        if (reponse && reponse.status === 200 && reponse.type === 'basic') {
          var copie = reponse.clone();
          caches.open(CACHE).then(function (cache) { cache.put(requete, copie); });
        }
        return reponse;
      }).catch(function () {
        if (enCache) { return enCache; }
        if (requete.mode === 'navigate') { return caches.match('index.html'); }
        return new Response('', { status: 504, statusText: 'Hors connexion' });
      });
      return enCache || reseau;
    })
  );
});
